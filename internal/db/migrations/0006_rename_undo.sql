-- SCHEMA-REVERSIBLE, NOT OPERATIONALLY REVERSIBLE — same caveat 0005 documents.
-- The statements below are correct and safe *as schema*. That is the narrow claim.
-- Dropping this table discards the ONLY record of any Apply's pre-Apply state: the
-- pre-Apply source path, the pre-Apply library row snapshots, and the pre-Apply
-- proposal rows. Nothing else in the schema carries them, so every still-undoable
-- Apply becomes permanently un-undoable the moment this runs. No file is moved and
-- no library row is changed (this table is write-then-read-only; nothing else joins
-- to it), so this is capability loss, not data corruption — but it cannot be undone
-- by re-running the Up block.
-- SAFE ROLLBACK PATH: leave 0006 applied and revert the application binary only — an
-- old binary against a 0006 database is a clean no-op (goose's dbMaxVersion gate).
-- Never hand-delete the 0006 row from goose_db_version without dropping the table:
-- goose.Up is called with no allowMissing option, so a gap below dbMaxVersion is a
-- hard startup error.
-- Index drops precede the table drop, matching 0003/0005's ordering.
DROP INDEX IF EXISTS idx_rename_undo_archive_mode_active;
DROP INDEX IF EXISTS idx_rename_undo_archive_mode_proposal;
DROP TABLE IF EXISTS rename_undo_archive;
