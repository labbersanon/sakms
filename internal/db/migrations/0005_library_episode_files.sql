--     every promotion.
-- Dropping this table discards the only record tying a demoted file to its episode slot. The
-- file is not deleted (nothing in this feature ever deletes a file) — it becomes an untracked
-- orphan under a mangled name that the next Scan re-proposes as a fresh duplicate. That is
-- operational churn, not data loss, and the Down block cannot undo it.
-- SAFE ROLLBACK PATH: leave 0005 applied and revert the application binary only — an old
-- binary against a 0005 database is a clean no-op (goose's dbMaxVersion gate). Never hand-delete
-- the 0005 row from goose_db_version without dropping the table: goose.Up is called with no
-- allowMissing option, so a gap below dbMaxVersion is a hard startup error.
-- Index drops precede the table drop, matching 0003's ordering.
DROP INDEX IF EXISTS library_episode_files_episode_id;
DROP INDEX IF EXISTS library_episode_files_one_primary;
DROP TABLE IF EXISTS library_episode_files;
