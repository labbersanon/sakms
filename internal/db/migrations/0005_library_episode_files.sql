-- Troubleshooting: UNIQUE(series_id, season_number, episode_number) on library_episodes is kept;
--   library_episodes.file_path stays the DENORMALIZED PRIMARY, exactly as library_items.file_path is.
-- Review if: library_episodes.file_path stops being the denormalized primary, or Purge/Dedup gain
--   alternate awareness (see .omc/plans/autopilot-impl.md §11).

CREATE TABLE library_episode_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id bigint NOT NULL,
    file_path text NOT NULL,
    is_primary boolean NOT NULL DEFAULT false,
    quality_tier text NOT NULL DEFAULT '',
    size bigint NOT NULL DEFAULT 0,
    width integer NOT NULL DEFAULT 0,
    height integer NOT NULL DEFAULT 0,
    video_codec text NOT NULL DEFAULT '',
    bitrate bigint NOT NULL DEFAULT 0,
    duration_sec double precision NOT NULL DEFAULT 0,
    phash text NOT NULL DEFAULT '',
    created_at text NOT NULL DEFAULT sakms_now(),
    updated_at text NOT NULL DEFAULT sakms_now(),
    FOREIGN KEY (episode_id) REFERENCES library_episodes (id) ON DELETE CASCADE ON UPDATE NO ACTION DEFERRABLE INITIALLY IMMEDIATE,
    -- NOT UNIQUE(file_path), unlike library_item_files. A logical-episode-split file
    -- (rename.RelocateEpisodeRange) legitimately backs SEVERAL library_episodes rows at one
    -- path, so a bare UNIQUE(file_path) would make the backfill below fail outright.
    UNIQUE (episode_id, file_path)
);

CREATE UNIQUE INDEX library_episode_files_one_primary
    ON library_episode_files (episode_id)
    WHERE is_primary;

CREATE INDEX library_episode_files_episode_id ON library_episode_files (episode_id);

-- Backfill one primary file row per existing episode that has a path. A range file's
-- N episode rows produce N primary rows (one per episode_id, same path) — deliberate:
-- each episode slot owns exactly one primary, which is what the partial index enforces.
INSERT INTO library_episode_files (
    episode_id, file_path, is_primary, quality_tier, size, phash
)
SELECT id, file_path, true, quality_tier, size, phash
FROM library_episodes
WHERE file_path <> '';

